import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import { createServer } from "node:http";
import { randomBytes } from "node:crypto";
import pg from "pg";
import { createBookingRouter } from "../src/routes/bookings.js";
import { createConcertRouter } from "../src/routes/concerts.js";
import { createPaymentRouter } from "../src/routes/payments.js";

const { Pool } = pg;
const databaseUrl = process.env.KONSERKITA_TEST_DATABASE_URL;

test("PostgreSQL isolasi: stok, rollback, idempotency dan payment bersamaan", {
  skip: !databaseUrl,
}, async () => {
  const target = new URL(databaseUrl);
  const host = target.hostname.replace(/^\[|\]$/g, "").toLowerCase();
  const databaseName = decodeURIComponent(target.pathname.slice(1));
  assert.ok(["127.0.0.1", "localhost", "::1"].includes(host), "integration test hanya boleh memakai loopback");
  assert.equal(databaseName, "konserkita_batch2_test", "database harus khusus untuk integration test ini");

  const bootstrapPool = new Pool({ connectionString: databaseUrl, max: 2 });
  let applicationPool;
  let server;
  let schema;

  try {
    const identity = await bootstrapPool.query(
      "SELECT current_database() AS database_name, host(inet_server_addr()) AS server_address",
    );
    assert.equal(identity.rows[0].database_name, "konserkita_batch2_test");
    assert.ok(["127.0.0.1", "::1"].includes(identity.rows[0].server_address));

    const existingRelations = await bootstrapPool.query(
      "SELECT count(*)::int AS count FROM pg_tables WHERE schemaname = 'public'",
    );
    assert.equal(existingRelations.rows[0].count, 0, "database test harus kosong sebelum test membuat schema");

    schema = `kk_batch2_it_${randomBytes(8).toString("hex")}`;
    await bootstrapPool.query(`CREATE SCHEMA "${schema}"`);
    applicationPool = new Pool({
      connectionString: databaseUrl,
      options: `-c search_path=${schema},public`,
      max: 12,
    });

    await applicationPool.query(`
      CREATE TABLE concerts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug VARCHAR(120) NOT NULL UNIQUE,
        title VARCHAR(200) NOT NULL,
        artist VARCHAR(200) NOT NULL,
        category VARCHAR(80) NOT NULL,
        city VARCHAR(100) NOT NULL,
        venue VARCHAR(200) NOT NULL,
        event_date DATE NOT NULL,
        event_time TIME NOT NULL,
        accent VARCHAR(30) NOT NULL DEFAULT 'blue',
        image_url TEXT NOT NULL,
        description TEXT NOT NULL,
        archived_at TIMESTAMPTZ,
        cancelled_at TIMESTAMPTZ,
        cancellation_reason VARCHAR(500)
      );
      CREATE TABLE ticket_categories (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        concert_id BIGINT NOT NULL REFERENCES concerts(id),
        name VARCHAR(80) NOT NULL,
        price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
        quota INTEGER NOT NULL CHECK (quota >= 0),
        archived_at TIMESTAMPTZ
      );
      CREATE TABLE bookings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        booking_code VARCHAR(40) NOT NULL UNIQUE,
        user_id BIGINT,
        ticket_category_id BIGINT NOT NULL REFERENCES ticket_categories(id),
        customer_name VARCHAR(150) NOT NULL,
        customer_email VARCHAR(254) NOT NULL,
        quantity INTEGER NOT NULL,
        unit_price NUMERIC(12,2) NOT NULL,
        total_price NUMERIC(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
        status VARCHAR(20) NOT NULL DEFAULT 'pending',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      );
      CREATE TABLE payments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id),
        status VARCHAR(20) NOT NULL DEFAULT 'pending',
        amount NUMERIC(14,2) NOT NULL,
        payment_method VARCHAR(50) NOT NULL DEFAULT 'simulation',
        expires_at TIMESTAMPTZ NOT NULL,
        paid_at TIMESTAMPTZ,
        failed_at TIMESTAMPTZ,
        expired_at TIMESTAMPTZ,
        quota_restored_at TIMESTAMPTZ,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      );
      CREATE TABLE digital_tickets (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        booking_id BIGINT NOT NULL REFERENCES bookings(id),
        ticket_number INTEGER NOT NULL,
        ticket_code VARCHAR(80) NOT NULL UNIQUE,
        status VARCHAR(16) NOT NULL DEFAULT 'issued',
        issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        used_at TIMESTAMPTZ,
        UNIQUE (booking_id, ticket_number)
      );
      CREATE TABLE payment_status_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        payment_id BIGINT NOT NULL REFERENCES payments(id),
        previous_status VARCHAR(20) NOT NULL,
        new_status VARCHAR(20) NOT NULL,
        changed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
        CHECK (previous_status <> new_status)
      );
      CREATE FUNCTION record_payment_status_change() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN
        IF OLD.status IS DISTINCT FROM NEW.status THEN
          INSERT INTO payment_status_history(payment_id,previous_status,new_status)
          VALUES (NEW.id,OLD.status,NEW.status);
        END IF;
        RETURN NEW;
      END;
      $$;
      CREATE TRIGGER payments_status_history_after_update AFTER UPDATE OF status ON payments
      FOR EACH ROW EXECUTE FUNCTION record_payment_status_change();
    `);

    const concert = await applicationPool.query(
      `INSERT INTO concerts (slug,title,artist,category,city,venue,event_date,event_time,image_url,description)
       VALUES ('integration-concert','Integration Concert','Test Performer; Guest Performer','Music','Test City','Test Venue','2030-01-01','19:00','https://example.test/poster','Integration fixture')
       RETURNING id`,
    );
    await applicationPool.query(
      `INSERT INTO ticket_categories (concert_id,name,price,quota)
       VALUES ($1,'Stock race',100,5),($1,'Idempotency race',200,5),($1,'Rollback fixture',123,3)`,
      [concert.rows[0].id],
    );

    const app = express();
    app.use(express.json());
    app.use("/api/concerts", createConcertRouter({ pool: applicationPool }));
    app.use("/api/bookings", createBookingRouter({ pool: applicationPool, logger: { error() {} } }));
    app.use("/api/payments", createPaymentRouter({ pool: applicationPool }));
    server = createServer(app);
    await new Promise((resolve, reject) => {
      server.once("error", reject);
      server.listen(0, "127.0.0.1", resolve);
    });
    const baseUrl = `http://127.0.0.1:${server.address().port}`;
    const concertResponse = await fetch(`${baseUrl}/api/concerts/integration-concert`);
    const concertBody = await concertResponse.json();
    assert.equal(concertResponse.status, 200);
    assert.equal(concertBody.data.artist, "Test Performer; Guest Performer");
    assert.deepEqual(concertBody.data.lineup, ["Test Performer", "Guest Performer"]);

    const postBooking = (ticketCategoryId, quantity, idempotencyKey) => fetch(`${baseUrl}/api/bookings`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        ...(idempotencyKey ? { "Idempotency-Key": idempotencyKey } : {}),
      },
      body: JSON.stringify({ customerName: "Integration Buyer", customerEmail: "buyer@example.test", ticketCategoryId, quantity }),
    });

    const stockRace = await Promise.all(Array.from({ length: 8 }, () => postBooking("1", 2)));
    assert.deepEqual(stockRace.map((response) => response.status).sort(), [201,201,409,409,409,409,409,409]);
    const stockState = await applicationPool.query(
      `SELECT tc.quota, count(b.id)::int AS booking_count,
              coalesce(sum(b.quantity),0)::int AS booked_quantity,
              count(p.id)::int AS payment_count,
              bool_and(b.unit_price = 100 AND p.amount = b.total_price) AS prices_consistent
       FROM ticket_categories tc
       LEFT JOIN bookings b ON b.ticket_category_id = tc.id
       LEFT JOIN payments p ON p.booking_id = b.id
       WHERE tc.name = 'Stock race'
       GROUP BY tc.id`,
    );
    assert.deepEqual(stockState.rows[0], {
      quota: 1,
      booking_count: 2,
      booked_quantity: 4,
      payment_count: 2,
      prices_consistent: true,
    });

    const idempotencyKey = "batch2-integration-key-0001";
    const duplicateRequests = await Promise.all([
      postBooking("2", 2, idempotencyKey),
      postBooking("2", 2, idempotencyKey),
    ]);
    assert.deepEqual(duplicateRequests.map((response) => response.status).sort(), [200,201]);
    const duplicateBodies = await Promise.all(duplicateRequests.map((response) => response.json()));
    assert.equal(duplicateBodies[0].data.bookingCode, duplicateBodies[1].data.bookingCode);
    assert.equal((await postBooking("2", 3, idempotencyKey)).status, 409);

    const bookingCode = duplicateBodies.find((body) => body.success && body.data.status === "pending").data.bookingCode;
    const attempt = () => fetch(`${baseUrl}/api/payments/${bookingCode}/attempt`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ outcome: "success" }),
    });
    const paymentAttempts = await Promise.all([attempt(), attempt()]);
    assert.deepEqual(paymentAttempts.map((response) => response.status), [503,503]);
    const pendingState = await applicationPool.query(
      `SELECT b.status AS booking_status, p.status AS payment_status,
              count(DISTINCT p.id)::int AS payment_count,
              count(DISTINCT t.id)::int AS ticket_count,
              tc.quota
       FROM bookings b
       JOIN payments p ON p.booking_id = b.id
       JOIN ticket_categories tc ON tc.id = b.ticket_category_id
       LEFT JOIN digital_tickets t ON t.booking_id = b.id
       WHERE b.booking_code = $1
       GROUP BY b.id, p.id, tc.id`,
      [bookingCode],
    );
    assert.deepEqual(pendingState.rows[0], {
      booking_status: "pending",
      payment_status: "pending",
      payment_count: 1,
      ticket_count: 0,
      quota: 3,
    });
    const paymentHistory = await applicationPool.query(`SELECT previous_status,new_status FROM payment_status_history h JOIN payments p ON p.id=h.payment_id JOIN bookings b ON b.id=p.booking_id WHERE b.booking_code=$1`, [bookingCode]);
    assert.deepEqual(paymentHistory.rows, []);

    await applicationPool.query(`
      CREATE FUNCTION fail_fixture_payment() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN
        IF NEW.amount = 123 THEN RAISE EXCEPTION 'integration rollback fixture'; END IF;
        RETURN NEW;
      END;
      $$;
      CREATE TRIGGER fail_fixture_payment BEFORE INSERT ON payments
      FOR EACH ROW EXECUTE FUNCTION fail_fixture_payment();
    `);
    assert.equal((await postBooking("3", 1)).status, 500);
    const rollbackState = await applicationPool.query(
      `SELECT tc.quota, count(b.id)::int AS booking_count
       FROM ticket_categories tc
       LEFT JOIN bookings b ON b.ticket_category_id = tc.id
       WHERE tc.name = 'Rollback fixture'
       GROUP BY tc.id`,
    );
    assert.deepEqual(rollbackState.rows[0], { quota: 3, booking_count: 0 });

    await applicationPool.query("UPDATE concerts SET cancelled_at=clock_timestamp(),cancellation_reason='Integration cancellation' WHERE slug='integration-concert'");
    assert.equal((await postBooking("2", 1)).status, 404);
  } finally {
    if (server?.listening) {
      await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
    }
    await applicationPool?.end();
    if (schema) await bootstrapPool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await bootstrapPool.end();
  }
});

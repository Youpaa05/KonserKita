BEGIN;

CREATE TABLE IF NOT EXISTS concerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    artist VARCHAR(200) NOT NULL,
    category VARCHAR(80) NOT NULL,
    city VARCHAR(100) NOT NULL,
    venue VARCHAR(200) NOT NULL,
    event_date DATE NOT NULL,
    event_time TIME NOT NULL,
    accent VARCHAR(30) NOT NULL DEFAULT 'blue',
    image_url TEXT NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT concerts_slug_not_blank
        CHECK (LENGTH(TRIM(slug)) > 0),
    CONSTRAINT concerts_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT concerts_artist_not_blank
        CHECK (LENGTH(TRIM(artist)) > 0),
    CONSTRAINT concerts_category_not_blank
        CHECK (LENGTH(TRIM(category)) > 0),
    CONSTRAINT concerts_city_not_blank
        CHECK (LENGTH(TRIM(city)) > 0),
    CONSTRAINT concerts_venue_not_blank
        CHECK (LENGTH(TRIM(venue)) > 0),
    CONSTRAINT concerts_image_url_not_blank
        CHECK (LENGTH(TRIM(image_url)) > 0)
);

CREATE TABLE IF NOT EXISTS ticket_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    name VARCHAR(80) NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    quota INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ticket_categories_concert_fk
        FOREIGN KEY (concert_id)
        REFERENCES concerts(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT ticket_categories_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT ticket_categories_price_nonnegative
        CHECK (price >= 0),
    CONSTRAINT ticket_categories_quota_nonnegative
        CHECK (quota >= 0),
    CONSTRAINT ticket_categories_concert_name_unique
        UNIQUE (concert_id, name),
    CONSTRAINT ticket_categories_id_concert_unique
        UNIQUE (id, concert_id)
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(40) NOT NULL UNIQUE,
    ticket_category_id BIGINT NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    customer_email VARCHAR(254) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    total_price NUMERIC(14, 2)
        GENERATED ALWAYS AS (quantity * unit_price) STORED,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT bookings_ticket_category_fk
        FOREIGN KEY (ticket_category_id)
        REFERENCES ticket_categories(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT bookings_code_not_blank
        CHECK (LENGTH(TRIM(booking_code)) > 0),
    CONSTRAINT bookings_customer_name_not_blank
        CHECK (LENGTH(TRIM(customer_name)) > 0),
    CONSTRAINT bookings_email_not_blank
        CHECK (LENGTH(TRIM(customer_email)) > 0),
    CONSTRAINT bookings_quantity_positive
        CHECK (quantity > 0),
    CONSTRAINT bookings_unit_price_nonnegative
        CHECK (unit_price >= 0),
    CONSTRAINT bookings_status_valid
        CHECK (status IN ('pending', 'confirmed', 'cancelled'))
);

CREATE INDEX IF NOT EXISTS idx_concerts_date
    ON concerts (event_date);

CREATE INDEX IF NOT EXISTS idx_concerts_city_category
    ON concerts (city, category);

CREATE INDEX IF NOT EXISTS idx_ticket_categories_concert
    ON ticket_categories (concert_id);

CREATE INDEX IF NOT EXISTS idx_bookings_ticket_category
    ON bookings (ticket_category_id);

CREATE INDEX IF NOT EXISTS idx_bookings_created_at
    ON bookings (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_bookings_status
    ON bookings (status);

COMMIT;
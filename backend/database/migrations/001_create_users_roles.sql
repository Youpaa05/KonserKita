-- KonserKita Fase 02
-- Migration 001: roles, users, and optional booking ownership.
-- Existing guest bookings remain valid.

CREATE TABLE public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT roles_name_not_blank
        CHECK (length(TRIM(name)) > 0),

    CONSTRAINT roles_name_unique
        UNIQUE (name)
);

CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT users_role_fk
        FOREIGN KEY (role_id)
        REFERENCES public.roles(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT users_name_not_blank
        CHECK (length(TRIM(name)) > 0),

    CONSTRAINT users_email_not_blank
        CHECK (length(TRIM(email)) > 0),

    CONSTRAINT users_password_hash_not_blank
        CHECK (length(TRIM(password_hash)) > 0)
);

-- Email unik tanpa membedakan huruf besar dan kecil.
CREATE UNIQUE INDEX users_email_lower_unique_idx
    ON public.users (LOWER(email));

CREATE INDEX users_role_id_idx
    ON public.users (role_id);

-- Nullable: booking tamu dan data lama tidak memerlukan user_id.
-- Jika akun dihapus, booking historis tetap dipertahankan sebagai guest.
ALTER TABLE public.bookings
    ADD COLUMN user_id BIGINT;

ALTER TABLE public.bookings
    ADD CONSTRAINT bookings_user_fk
    FOREIGN KEY (user_id)
    REFERENCES public.users(id)
    ON UPDATE CASCADE
    ON DELETE SET NULL;

CREATE INDEX bookings_user_id_idx
    ON public.bookings (user_id);


-- Simpan transisi status payment yang terjadi setelah migrasi ini diterapkan.
-- Histori lama tidak direka ulang dari status payment saat ini.
CREATE TABLE public.payment_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES public.payments(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    previous_status VARCHAR(20) NOT NULL,
    new_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT payment_history_previous_status_valid CHECK (previous_status IN ('pending','paid','failed','expired')),
    CONSTRAINT payment_history_new_status_valid CHECK (new_status IN ('pending','paid','failed','expired')),
    CONSTRAINT payment_history_status_changed CHECK (previous_status <> new_status)
);

CREATE INDEX payment_status_history_payment_changed_idx
    ON public.payment_status_history (payment_id, changed_at, id);

CREATE FUNCTION public.record_payment_status_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO public.payment_status_history (payment_id, previous_status, new_status)
        VALUES (NEW.id, OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER payments_status_history_after_update
AFTER UPDATE OF status ON public.payments
FOR EACH ROW EXECUTE FUNCTION public.record_payment_status_change();

CREATE TABLE public.admin_role_change_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    target_user_id BIGINT REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    previous_role VARCHAR(50) NOT NULL,
    new_role VARCHAR(50) NOT NULL,
    affected_sessions INTEGER NOT NULL DEFAULT 0 CHECK (affected_sessions >= 0),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX admin_role_change_audit_changed_idx
    ON public.admin_role_change_audit (changed_at DESC, id DESC);

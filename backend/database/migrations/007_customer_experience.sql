CREATE TABLE public.concert_favorites (
    user_id BIGINT NOT NULL
        REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    concert_id BIGINT NOT NULL
        REFERENCES public.concerts(id) ON UPDATE CASCADE ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT concert_favorites_user_concert_unique UNIQUE (user_id, concert_id)
);

CREATE INDEX concert_favorites_user_created_idx
    ON public.concert_favorites (user_id, created_at DESC);

CREATE TABLE public.user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE CASCADE,
    event_key VARCHAR(160) NOT NULL,
    type VARCHAR(40) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    booking_code VARCHAR(40),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    read_at TIMESTAMPTZ,
    CONSTRAINT user_notifications_event_key_unique UNIQUE (user_id, event_key),
    CONSTRAINT user_notifications_type_valid CHECK (
        type IN ('booking_created', 'payment_paid', 'ticket_issued')
    ),
    CONSTRAINT user_notifications_event_key_not_blank CHECK (length(trim(event_key)) > 0),
    CONSTRAINT user_notifications_title_not_blank CHECK (length(trim(title)) > 0),
    CONSTRAINT user_notifications_message_not_blank CHECK (length(trim(message)) > 0)
);

CREATE INDEX user_notifications_unread_idx
    ON public.user_notifications (user_id, created_at DESC)
    WHERE read_at IS NULL;

CREATE INDEX user_notifications_user_created_idx
    ON public.user_notifications (user_id, created_at DESC, id DESC);

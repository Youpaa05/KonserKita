CREATE TABLE public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES public.bookings(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    amount NUMERIC(14, 2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'simulation',
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,
    expired_at TIMESTAMPTZ,
    quota_restored_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT payments_status_valid CHECK (status IN ('pending', 'paid', 'failed', 'expired')),
    CONSTRAINT payments_amount_nonnegative CHECK (amount >= 0),
    CONSTRAINT payments_method_not_blank CHECK (length(trim(payment_method)) > 0)
);

CREATE INDEX payments_status_expiry_idx ON public.payments (status, expires_at);

-- Create the one-to-one payment record for bookings created before this migration.
INSERT INTO public.payments (
    booking_id, status, amount, payment_method, expires_at,
    paid_at, failed_at, created_at, updated_at
)
SELECT
    b.id,
    CASE b.status
        WHEN 'confirmed' THEN 'paid'
        WHEN 'cancelled' THEN 'failed'
        ELSE 'pending'
    END,
    b.total_price,
    'simulation',
    b.created_at + INTERVAL '15 minutes',
    CASE WHEN b.status = 'confirmed' THEN b.updated_at END,
    CASE WHEN b.status = 'cancelled' THEN b.updated_at END,
    b.created_at,
    b.updated_at
FROM public.bookings AS b;

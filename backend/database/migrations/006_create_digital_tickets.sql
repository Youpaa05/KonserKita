CREATE TABLE public.digital_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL
        REFERENCES public.bookings(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    ticket_number INTEGER NOT NULL,
    ticket_code VARCHAR(80) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'issued',
    issued_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    used_at TIMESTAMPTZ,
    used_by BIGINT
        REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE SET NULL,

    CONSTRAINT digital_tickets_code_unique UNIQUE (ticket_code),
    CONSTRAINT digital_tickets_booking_number_unique UNIQUE (booking_id, ticket_number),
    CONSTRAINT digital_tickets_number_positive CHECK (ticket_number > 0),
    CONSTRAINT digital_tickets_status_valid CHECK (status IN ('issued', 'used')),
    CONSTRAINT digital_tickets_usage_timestamp_consistent CHECK (
        (status = 'issued' AND used_at IS NULL) OR
        (status = 'used' AND used_at IS NOT NULL)
    )
);

CREATE INDEX digital_tickets_status_idx
    ON public.digital_tickets (status, issued_at);
